/**
 * Returns a deterministic daily wisdom item based on the date seed
 */
export function getDailyWisdom(date: Date = new Date(), category: string = 'all'): LifeWisdomItem {
  let list = LIFE_WISDOM_ITEMS;
  if (category && category !== 'all') {
    const filtered = list.filter((i) => i.category === category);
    if (filtered.length > 0) {
      list = filtered;
    }
  }

  // Deterministic seed based on day of year
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));

  const index = Math.abs(dayOfYear) % list.length;
  return list[index];
}

