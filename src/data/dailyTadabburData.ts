/**
 * الحصول على مادة التدبر اليومية بناءً على اليوم من السنة أو الترتيب
 */
export function getDailyTadabburItem(dayOffset: number = 0): DailyTadabburItem {
  const total = DAILY_TADABBUR_DATA.length;
  // Calculate day of year (1 - 365)
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = Math.abs((dayOfYear - 1 + dayOffset) % total);
  return DAILY_TADABBUR_DATA[index] || DAILY_TADABBUR_DATA[0];
}

/**
 * الحصول على مادة تدبر ليوم محدد برقم اليوم (1 - 7)
 */
export function getTadabburByDayNumber(num: number): DailyTadabburItem {
  const found = DAILY_TADABBUR_DATA.find((item) => item.dayNumber === num);
  return found || DAILY_TADABBUR_DATA[0];
}
